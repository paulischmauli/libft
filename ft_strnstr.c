#include "libft.h"

char	*ft_strnstr(const char *big, const char *little, size_t len)
{
	size_t	i;
	size_t	j;

	if (!*little)
		return ((char *)big);
	i = -1;
	while (++i < len && big[i])
	{
		j = 0;
		if (big[i] == little[j])
		{
			while (i + j < len && big[i + j] == little[j] && little[j])
				j++;
			if (!little[j])
				return ((char *) big + i);
		}
	}
	return (NULL);
}
